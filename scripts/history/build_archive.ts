/**
 * Builds the History Board's archive (Phase E): every player's season line and every playoff
 * series for the shared history, 1972-2026, so the board never replays seasons in the browser.
 *   src/sports/history/data/archive.json
 * Derived only: the same games and stats as Phases B-D (seasonStats of each generated season),
 * stored compactly. Tests check it against a fresh replay. Run after build_forward.ts:
 *   npx vite-node scripts/history/build_archive.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { leagueById, type Sport } from '../../src/sports/demo';
import type { HistoryData } from '../../src/sports/history/data';
import { freeSeason, mergeForward, type ForwardData } from '../../src/sports/history/forward';
import { historySeason, type HistorySeason } from '../../src/sports/history/games';
import { seasonStats, type StatLine } from '../../src/sports/history/stats';

const read = (f: string) => JSON.parse(readFileSync(f, 'utf8'));
const data: HistoryData = { players: read('src/sports/history/data/players.json').players, seasons: read('src/sports/history/data/seasons.json').seasons };
const fwd: ForwardData = read('src/sports/history/data/forward.json');
const merged = mergeForward(data, fwd);
const t0 = performance.now();

const keys: Record<Sport, Set<string>> = { baseball: new Set(), basketball: new Set(), football: new Set(), hockey: new Set() };
const raw: { id: string; sport: Sport; h: HistorySeason; lines: { playerId: string; teamId: string; regular: StatLine; playoffs: StatLine }[] }[] = [];
for (const s of [...data.seasons, ...fwd.seasons]) {
  const sport = leagueById(s.league).sport;
  const src = s.year <= 2025 ? data : merged;
  const h = s.year <= 2025 ? historySeason(src, s) : freeSeason(merged, s);
  const st = seasonStats(src, h).players;
  for (const p of st) for (const k of [...Object.keys(p.regular), ...Object.keys(p.playoffs)]) keys[sport].add(k);
  raw.push({ id: s.id, sport, h, lines: st });
}
const keyList = Object.fromEntries(Object.entries(keys).map(([k, v]) => [k, [...v].sort()])) as Record<Sport, string[]>;
const index = new Map(merged.players.map((p, i) => [p.i, i]));
const pack = (sport: Sport, l: StatLine) => {
  const out = keyList[sport].map((k) => l[k] ?? 0);
  while (out.length && out[out.length - 1] === 0) out.pop();
  return out;
};
const seasons: Record<string, unknown> = {};
for (const { id, sport, h, lines } of raw) {
  const teams: Record<string, { r: number[][]; p?: number[][] }> = {};
  for (const l of lines.sort((a, b) => a.playerId.localeCompare(b.playerId))) {
    const t = (teams[l.teamId] ??= { r: [] });
    t.r.push([index.get(l.playerId)!, ...pack(sport, l.regular)]);
    if (Object.values(l.playoffs).some((v) => v > 0)) (t.p ??= []).push([index.get(l.playerId)!, ...pack(sport, l.playoffs)]);
  }
  const series = h.playoffs.map((x) => ({
    round: x.round, high: x.high, low: x.low, winner: x.winner, wins: [x.wins[x.high] ?? 0, x.wins[x.low] ?? 0],
    // Each game: home team is the higher seed? (1/0), home score, away score, overtime periods.
    games: x.games.map((g) => [g.home === x.high ? 1 : 0, g.result.homeScore, g.result.awayScore, g.result.ot]),
  }));
  seasons[id] = { teams, series };
}
const out = {
  note: 'Generated by scripts/history/build_archive.ts: season lines and playoff series of the shared history (1972-2026), derived from the generated games. Read-only.',
  keys: keyList,
  /** Player ids by index (the ledger players, then the 2026 and 2027 draftees). */
  players: merged.players.map((p) => p.i),
  seasons,
};
const text = JSON.stringify(out);
writeFileSync('src/sports/history/data/archive.json', `${text}\n`);
console.log(`seasons ${raw.length} · keys ${Object.entries(keyList).map(([k, v]) => `${k} ${v.length}`).join(', ')} · ${(text.length / 1024).toFixed(0)} KB · ${(performance.now() - t0).toFixed(0)} ms`);
